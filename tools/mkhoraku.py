def many(n):
    """短い横線を n 本、(300,200)-(400,300) の枠の中に並べます。"""
    out = []
    for i in range(n):
        y = 205.0 + i * 1.8
        out.append((250.0, y, 450.0, y))
    return out


def main():
    src, out = sys.argv[1], sys.argv[2]
    case = sys.argv[3] if len(sys.argv) > 3 else 'rects'
    # 'walls@pen' なら二本目の壁（線 2,3）のペンを変える、'walls@typ' なら線種
    kind = ''
    if '@' in case:
        case, kind = case.split('@', 1)
    segs = many(int(case[4:])) if case.startswith('many') else CASES[case]
    j = Jwc(src)
    j.banish('points')
    for i in range(j.n_lines):
        p = j.at + i * 22
        if i < len(segs):
            x0, y0, x1, y1 = segs[i]
            struct.pack_into('<ffff', j.d, p,
                             x0 - AX, AY - y0, x1 - AX, AY - y1)
            j.d[p + 16] = 1         # 線種 実線
            j.d[p + 17] = 1         # ペン
            if kind == 'pen' and i >= 2:
                j.d[p + 17] = 3
            if kind == 'typ' and i >= 2:
                j.d[p + 16] = 2
            j.d[p + 18] = 0         # レイヤ
            j.d[p + 19] = 0x41
            j.d[p + 20] = 0
            j.d[p + 21] = 0
        else:
            struct.pack_into('<ffff', j.d, p, FAR, FAR, FAR + 1.0, FAR)
    open(out, 'wb').write(bytes(j.d))
    print('wrote', out, case, len(segs), 'lines')


main()
